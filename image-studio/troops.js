'use strict';
/* 行军部队精灵。
   8 方向只生成 5 张：正南、东南、正东、东北、正北。
   水平镜像后得到西南、正西、西北——镜像映射 E↔W、SE↔SW、NE↔NW，南北自身对称。
   剩下三个方向白送，一致性风险也少三张。

   队列里不画旗。势力颜色靠运行时把现成的 10 面旗贴在队伍上方——
   否则 10 势力 × 8 方向 = 80 张，不可行。 */

