  '题材是中国汉末三国时代一支正在行军的小队，用作策略地图上移动的部队标记。' +
  '固定采用等距斜俯视角（约 45 度俯角，从东南方向看去），与同一套地图素材的视角完全一致。' +
  '主光来自画面左上方，阴影朝右下投射，阴影里带冷调环境色。' +
  '队伍构成固定：最前面一名骑马的军官，后面跟着四名披甲步卒排成纵队，' +
  '步卒肩扛长戟，腰悬环首刀，军官按剑。' +
  '汉末形制：札甲或皮甲，束发戴巾帻，马不配马镫（马镫要到三四世纪才有）。' +
  '配色必须中性：甲片是冷铁灰，战袍是土褐与赭，马是栗色，' +
  '**不要出现任何鲜艳的旗帜或势力色**——队伍里一面旗也不许有。' +
  '队伍完整置于画面中央，四周留出余白，不被边缘裁切，脚下不画地面也不画影子。' +
  '背景完全透明，只有这支队伍本身。' +
  '画面中不得出现任何文字、字母、汉字、签名、水印、边框或UI元素。';

const T_NEG =
  '绝对禁止：黑白、灰度、单色、素描、去饱和、照片写实、3D渲染感。' +
  '避免：旗帜、锦旗、幡旗、鲜艳颜色、明清或唐代的甲胄样式、马镫、' +
  '日式武士、欧洲骑士、动漫平涂、正面平视视角、俯视正投影、' +
  '地面、草地、影子、不透明的背景色块、队伍被边缘裁切。';

/* [key, 方位名, 朝向描述] —— 另外三个方向由这五张水平镜像得到 */
const DIRS = [
  ['s',  '正南', '整队朝画面正下方行进，面朝观者，能看清人和马的正面'],
  ['se', '东南', '整队朝画面右下方斜行，呈四分之三正面，能看到人物的正面与右侧'],
  ['e',  '正东', '整队朝画面正右方行进，完全是侧面剪影，人与马都是正侧向'],
  ['ne', '东北', '整队朝画面右上方斜行，呈四分之三背面，主要看到人物的背部与右侧'],
  ['n',  '正北', '整队朝画面正上方行进，背对观者，只看得到人和马的背影'],
];

function buildTroopItems() {
  return DIRS.map(([k, name, face]) => ({
    id: 'troop_' + k, category: 'troop',
    label: '行军部队·' + name,
    meta: { 方位: name, 说明: '水平镜像可得对应的西向' },
    source: null, size: '1024x1024', background: 'transparent',
    prompt: T_ANCHOR + '\n\n【朝向】' + face + '。\n\n' + T_NEG,
    status: 'idle', attempts: 0,
  }));
}
module.exports = { DIRS, buildTroopItems };
