function buildFlagItems() {
  const items = [];
  items.push({
    id: 'flag_master', category: 'flag', label: '牙旗·形状母版',
    meta: { 用途: '派生参考图', 色名: '素白' },
    source: null, size: '1024x1024', background: 'transparent',
    prompt: FLAG_ANCHOR + '\n\n' + MASTER_BODY + '\n\n' + FLAG_NEG,
    status: 'idle', attempts: 0,
  });
  for (const [key, use, colorName, hex, desc] of FLAGS) {
    items.push({
      id: 'flag_' + key, category: 'flag', label: '牙旗·' + use,
      meta: { 用途: use, 色名: colorName, 色值: hex },
      source: null, refItem: 'flag_master',
      size: '1024x1024', background: 'transparent',
      prompt: deriveFlag(desc) + '\n\n' + FLAG_NEG,
      status: 'idle', attempts: 0,
    });
  }
  return items;
}

