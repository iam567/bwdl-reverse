function cgPrompt(idx) {
  const list = idx.map((i, k) => `${k + 1}. ${SCENES[i][0]}：${SCENES[i][1]}`).join('\n');
  return '像素画（pixel art）风格的**四格插图表**，用于中式历史策略游戏「使用计策」时弹出的效果图。\n' +
    '**画面严格划分成 2 列 × 2 行、共 4 个等大的横幅方格**，每格 768×512，' +
    '格与格之间不画边框线也不画分隔线，**每格是一幅独立的完整画面、铺满整格、不留白边**。\n\n' +
    '【四格，从左到右、从上到下】\n' + list + '\n\n' +
    '每格都是**电影感的横幅构图**：主体占画面中心，有明确的前景 / 中景 / 远景，' +
    '强对比、饱和的主色（火计火箭劫火是橙红，水攻乱水是青灰，奇门遁甲是暗红雾，其余按场景）。' +
    '汉末形制：札甲、巾帻、旌旗、木栅营寨，不要明清飞檐、不要日式甲。\n' +
    '**严格的像素网格**，硬边、不做抗锯齿与渐变，色板受限，像素点成簇排布。\n' +
    '画面中不得出现任何文字、字母、汉字、签名、水印、边框或UI元素。';
}

const buildCg = k => ({
  id: 'pcg_' + k, category: 'plotcg',
  label: '计策效果图·' + SHEETS[k].map(i => SCENES[i][0]).join('/'),
  meta: { 格数: 4, 计策: SHEETS[k].join(',') },
  source: null, size: '1536x1024',
  prompt: cgPrompt(SHEETS[k]), status: 'idle', attempts: 0,
});
const buildCgAll = () => SHEETS.map((_, k) => buildCg(k));

