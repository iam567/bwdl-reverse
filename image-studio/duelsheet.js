'use strict';
/* 单挑立绘改用「一张整图出六帧、程序裁切」——原版 lib304 本来就是一张 900×60 的整图。
   一帧一张的做法出图 333 次；改成整图后 37 次，省了将近九成。
   实测 1536×1024 切 3×2（每格 512×512）模型能画得大小一致、切得干净，
   而且奔驰那两帧的马腿姿势确实不同，步频做得出来。

   六格只放动画真正用得上的帧，待机那帧已有母版，不重出：
     4 命中（突刺与命中合一）/ 7 爆发 / 9 受击 / 13 落马 / 11 奔驰腾空 / 14 奔驰落地 */

const { SKINS } = require('./duelskins.js');

const CELLS = [
  [4,  '命中', '兵器向右完全递出刺中，**锋刃处爆出一小簇白亮的光点**，马前腿抬起'],
  [7,  '爆发', '举兵器向上发力，**周身迸出金色的星芒与光块**，人马边缘镀金，气势最盛'],
  [9,  '受击', '身体后仰、失去平衡，兵器脱开防守位置，像是硬吃了一下'],
  [13, '落马', '**人与马一起倒地**：马侧翻四蹄朝右，人摔在马前，兵器脱手落在一旁'],
  [11, '奔驰·腾空', '**全速奔驰**：马前蹄高扬腾空、后腿蹬地，身体前倾，鬃毛与尾巴向后飞扬'],
  [14, '奔驰·落地', '**全速奔驰的另一相**：马四蹄收拢到身下几乎同时离地，背部拱起，骑手压得更低'],
];

function sheetPrompt(skinKey) {
  const look = SKINS[skinKey][2];
  const list = CELLS.map(([, n, d], i) => `${i + 1}. ${n}：${d}`).join('\n');
  return '像素画（pixel art）风格的**精灵表（sprite sheet）**，用于策略游戏的单挑演出。\n' +
    '**画面严格划分成 3 列 × 2 行、共 6 个等大的方格**，每格 512×512，' +
    '格与格之间不画边框线也不画分隔线，但**每格里的角色必须完整、不越界、不跨格**。\n' +
    '**六格画的是同一个人同一匹马**，只有动作不同；' +
    '**每格里角色的大小、站位、地平线高度必须完全一致**，像同一台摄影机拍的连续帧。\n\n' +
    '【角色】' + look + '\n\n【六格的动作，从左到右、从上到下】\n' + list + '\n\n' +
    '**正侧面视角，一律面朝右方。**\n' +
    // 逐帧那版有限色与成簇排布的要求，整图这版我漏了，出来就偏厚涂、偏平滑
    '**严格的像素网格**：每个像素都是清晰的方块，边缘硬阶梯状，绝不做抗锯齿与渐变；' +
    '色板受限，靠有限色阶表现明暗，像素点成簇排布。\n' +
    '**配色要饱和、要有明确的主色**，不要整体发灰发糊——' +
    '哪怕主色是白或银，也要靠一处鲜明的点缀色（披风、缨、绶带、马具）把人物立起来。\n' +
    '**背景留空**：除了人和马什么都不要画，不要地面、不要布景，' +
    '**更不要画表示透明的灰白棋盘格**。\n' +
    '绝对禁止：文字、编号、边框、格线、水印。';
}

const buildSheet = k => ({
  id: 'dsh_' + k, category: 'duelsheet', label: '立绘整图·' + SKINS[k][0],
  meta: { 外观: SKINS[k][0], 格数: 6 },
  source: null, size: '1536x1024', background: 'transparent',
  prompt: sheetPrompt(k), status: 'idle', attempts: 0,
});

module.exports = { CELLS, buildSheet, sheetPrompt };
