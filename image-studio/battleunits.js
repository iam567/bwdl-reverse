'use strict';
/* 战场单位精灵。
   原版是 lib51 那张 11 列 × 6 行的方块表：列 = 兵力÷100（0–10），
   行 = 兵种×阵营，格子上直接写着数字和「平/水/山」。
   复刻改成真人小像，兵力另用血条表示。

   30 张生成：15 张蓝方母版（3 兵种 × 5 方向），红方全部从蓝方派生只改颜色。
   5 个方向水平镜像后覆盖 8 向（E↔W、SE↔SW、NE↔NW，南北自身对称）。

   兵种必须靠**剪影与装备**区分，不能靠颜色——颜色要留给敌我。 */

const U_ANCHOR =
  '像素画（pixel art）风格的游戏单位小像，用于策略游戏的战棋战场。' +
  '**严格的 64×64 像素网格**：每一个像素都是清晰的方块，边缘硬朗呈阶梯状，' +
  '绝对不做抗锯齿、不做柔化、不做渐变。色板受限，只用 12 到 16 种颜色。' +
  '视角是**略带俯角的四分之三视**（约 60 度俯角）：' +
  '地面是正俯视的，但人物要稍微立起来，能看清头、肩、兵器与衣饰——' +
  '完全的正俯视只能看到头顶，认不出是什么兵。' +
  '画面里只有**一名士兵**，站立或迈步的姿态，居中，占画面高度的八成，' +
  '脚下不画地面、不画影子、不画底座。' +
  '汉末形制：札甲或皮甲，束发戴巾帻，不戴明清或日式头盔。' +
  '背景完全透明，只有这名士兵本身。' +
  '画面中不得出现任何文字、字母、汉字、签名、水印、边框或UI元素。';

const U_NEG =
  '绝对禁止：抗锯齿、模糊、渐变、柔和阴影、照片写实、厚涂、3D渲染、' +
  '矢量插画、卡通粗描边、等距斜视角、完全的正俯视（只见头顶）。' +
  '避免：多个人物、马匹、旗帜杆、地面、影子、底座圆环、' +
  '日式武士甲、欧洲板甲、明清号衣、不透明的背景色块、被边缘裁切。';

/* 兵种靠装备与体态区分，蓝方统一着「靛蓝战袍」 */
const ARMS = [
  ['ping', '平军', '重装步卒：身披厚实的札甲，左手持一面高大的方盾，右手握长戟，' +
                   '体态方正厚重，是三种兵里最壮实的'],
  ['shui', '水军', '水战之卒：只着轻便的皮甲，头戴宽边斗笠，左手圆盾右手短刀，' +
                   '腰间别着一支船桨，体态轻捷'],
  ['shan', '山军', '山地之卒：兽皮与皮甲混穿，背一张长弓、腰悬短刀，' +
                   '小腿缠着行縢，身形瘦削灵活'],
];

const DIRS = [
  ['s',  '正南', '面朝观者站立，能看清正面的脸与装备'],
  ['se', '东南', '朝画面右下方，呈四分之三正面'],
  ['e',  '正东', '朝画面正右方，完全侧向'],
  ['ne', '东北', '朝画面右上方，呈四分之三背面'],
  ['n',  '正北', '背对观者，只看得到背影与背上的装备'],
];

const BLUE = '战袍、披风与盾面是明确的**靛蓝色**，甲片是冷铁灰，这是本方的识别色';
const deriveRed =
  '以参考图中的士兵为唯一依据，保持完全相同的姿势、朝向、体态、' +
  '甲胄与兵器的款式、像素网格与色块排布，就像同一位画师画的同一个兵换了身衣服。' +
  '唯一的改动是识别色：把战袍、披风与盾面的**靛蓝改成朱红**，' +
  '甲片的冷铁灰保持不变。' +
  '仍然是 64×64 的硬边像素画，不加抗锯齿、不加渐变。背景保持完全透明。' +
  '画面中不得出现任何文字、字母、汉字、签名、水印、边框或UI元素。';

function buildUnitItems() {
  const items = [];
  for (const [ak, aname, adesc] of ARMS)
    for (const [dk, dname, ddesc] of DIRS) {
      const id = 'u_blue_' + ak + '_' + dk;
      items.push({
        id, category: 'battleunit', label: '战场单位·蓝·' + aname + '·' + dname,
        meta: { 阵营:'我方', 兵种:aname, 方位:dname },
        source: null, size: '1024x1024', background: 'transparent',
        prompt: U_ANCHOR + '\n\n【兵种】' + adesc + '。' + BLUE + '。\n【朝向】' + ddesc + '。\n\n' + U_NEG,
        status: 'idle', attempts: 0,
      });
      items.push({
        id: 'u_red_' + ak + '_' + dk, category: 'battleunit',
        label: '战场单位·红·' + aname + '·' + dname,
        meta: { 阵营:'敌方', 兵种:aname, 方位:dname },
        source: null, refItem: id, size: '1024x1024', background: 'transparent',
        prompt: deriveRed, status: 'idle', attempts: 0,
      });
    }
  return items;
}
module.exports = { ARMS, DIRS, buildUnitItems };
