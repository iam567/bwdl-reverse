function build() {
  return Object.entries(CITIES).map(([id, [name, tier, desc]]) => ({
    id: `city_${id}`,
    category: 'city',
    label: name,
    meta: { 城市ID: +id, 等级: tier, 等级名: ['','帝都','州都','大郡城','郡城','边城','寨堡'][tier] },
    source: null,
    size: '1024x1024',
    background: 'transparent',
    prompt: `${CITY_ANCHOR}\n\n规模：${TIER_SCALE[tier]}。\n\n城池：${name}。${desc}。\n\n${NEG}`
  }));
}
module.exports = { build, CITIES, CITY_ANCHOR };

