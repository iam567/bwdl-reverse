const color = (c, ride) =>
  `战袍、束带${ride === '骑马' ? '与马鞯' : '与盾面'}是明确的**${c}**`;

function sheetPrompt(armKey) {
  const a = ARMS.find(x => x[0] === armKey);
  const cell = (side, di) =>
    `${side === 0 ? '红方' : '蓝方'}·${DIRS[di][1]}：${DIRS[di][2]}。` +
    `${a[6] ? a[6][di] : DIRS[di][3](a[4])}`;
  const list = [0, 1].flatMap(s => [0, 1, 2].map(d => cell(s, d)))
                     .map((s, i) => `${i + 1}. ${s}`).join('\n');
  return '像素画（pixel art）风格的**精灵表（sprite sheet）**，用于中式策略战棋游戏的阵型战。\n' +
    '**画面严格划分成 3 列 × 2 行、共 6 个等大的方格**，每格 512×512，' +
    '格与格之间不画边框线也不画分隔线，但**每格里的角色必须完整、居中、不越界、不跨格**。\n' +
    '**六格画的是同一个兵**（骑马的连马也是同一匹），同样的甲胄、同样的兵器、同样的体型；' +
    '**每格里角色的大小必须完全一致，脚底（或马蹄）都落在各自方格底部的同一高度**，' +
    '像同一台摄影机从三个方位拍的同一个人。\n' +
    '**上排三格是红方、下排三格是蓝方**，' +
    '上下两排除了这身识别色之外**不许有任何别的差别**——' +
    '姿势、朝向、装备、比例、像素排布都要一一对应。\n\n' +
    '【这个兵是什么】**' + a[3] + '**，兵器是**' + a[4] + '**。' + a[5] + '\n' +
    '【红方】' + color('朱红色', a[3]) + '，甲片是冷铁灰。\n' +
    '【蓝方】' + color('靛蓝色', a[3]) + '，甲片是冷铁灰。\n\n' +
    '【六格，从左到右、从上到下】\n' + list + '\n\n' +
    '视角是**略带俯视（约 15 度）的经典 RPG 行走图三视**：正面 / 背面 / 正侧面，' +
    '不是等距斜视角，也不是只见头顶的正俯视。\n' +
    '**这张图最终会缩到 64×64 显示**：所以要靠**剪影和大色块**辨识，' +
    '不要画五官细节、不要画细碎的纹样和铆钉；轮廓线要粗、要闭合、要和背景拉开对比。\n' +
    '**严格的像素网格**：每个像素都是清晰的方块，边缘硬阶梯状，绝不做抗锯齿与渐变；' +
    '色板受限，只用 12 到 16 色，靠有限色阶表现明暗，像素点成簇排布。\n' +
    '汉末形制：札甲或皮甲，束发戴巾帻，不戴明清或日式头盔，不穿欧洲板甲。\n' +
    '**背景留空**：除了这个兵（和马）什么都不要画，不要地面、不要影子、不要底座圆环、' +
    '不要旗帜，**更不要画表示透明的灰白棋盘格**。\n' +
    '**任何一格里都不许有任何东西越过本格的边界。**\n' +
    '绝对禁止：文字、编号、边框、格线、水印、多个人物挤在一格里。';
}

const buildSheet = k => {
  const a = ARMS.find(x => x[0] === k);
  return {
    id: 'ush_' + k, category: 'unitsheet', label: '阵型战小兵·' + a[2],
    meta: { 兵种: a[2], 兵种号: a[1], 乘骑: a[3], 格数: 6 },
    source: null, size: '1536x1024', background: 'transparent',
    prompt: sheetPrompt(k), status: 'idle', attempts: 0,
  };
};

const buildUnitSheets = () => ARMS.map(a => buildSheet(a[0]));

module.exports = { ARMS, DIRS, buildSheet, buildUnitSheets, sheetPrompt };
