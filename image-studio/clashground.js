'use strict';
/* 阵型战那层的地面。原版是 lib98：256×64 的一条，四格 64×64，
   褐土(平原) / 蓝水 / 绿地(山林) / 灰石(攻城)，直接平铺满整个战场。
   这是整个战斗画面里最后一块还在用原版素材的地方。

   四种拼在一张 1024×1024 里出（2×2、每格 512），一次出图。
   放一起还有个好处：四种地形的明度和饱和度会被模型拉到同一档，
   不会出现「平原很亮、山林很暗」这种一换地形整屏调子就跳的情况。

   两条是从地块那轮踩出来的坑，必须写死：
   一是**正俯视**——这层是战棋盘，不是场景画，有地平线就穿帮；
   二是**要暗、要匀**——上面要摆红蓝两色的小兵，
     底子一亮一花，兵就陷进去看不见了（南中那版亮砖红返工过三次）。 */

/* 水战那格不是水面，是**船甲板**——水战本来就是在船上打的，
   平铺开来整个战场就是连在一起的船阵，比画一片浅水说得通得多。 */
const CELLS = [
  ['ping', '草原', '连绵的草原：半高的青草被风梳成一道道，' +
                   '绿里透着黄，间或几丛更深的草窠和零星的小野花，' +
                   '草稀处才露出一点黄褐的土'],
  ['shui', '连环船', '**俯视的连环船阵**：几条战船并排系在一起，' +
                     '甲板是横铺的深褐船板、板缝里填着发黑的麻絮与桐油，' +
                     '船与船之间露出深青色的水面与细碎的波纹，' +
                     '相邻的船帮之间连着铁链与跳板，甲板上间或有铁环与盘起的缆绳'],
  ['shan', '山地', '高处的山地：大片裸露的灰褐岩面与碎石坡，' +
                   '石缝里长着稀疏的高山草与苔，' +
                   '岩石的层理和裂纹是主要的纹理'],
  ['gong', '城郭', '城墙内外被反复碾压的地面：夯实的灰黄土混着碎石与残破的青石板，' +
                   '有深深的车辙沟痕与几摊积水'],
];

function groundPrompt() {
  const list = CELLS.map(([, n, d], i) => `${i + 1}. ${n}：${d}`).join('\n');
  return '像素画（pixel art）风格的**地面材质表**，用于策略游戏战棋盘的地面。\n' +
    '**画面严格划分成 2 列 × 2 行、共 4 个等大的方格**，每格 512×512，' +
    '格与格之间不画边框线也不画分隔线。\n\n' +
    '【四格，从左到右、从上到下】\n' + list + '\n\n' +
    '**视角是完全的正俯视**——像从正上方垂直往下看地面，' +
    '所以**不许有地平线、不许有天空、不许有远景、不许有任何东西的侧面**。' +
    '这是铺在战棋盘上的地面材质，不是一张风景画。\n' +
    '**每一格都要能四边无缝平铺**：纹理要均匀铺满整格，' +
    '**不许有一个显眼的主体物**（大石头、一棵树、一个水坑都不行）——' +
    '平铺开来就会变成一片规律的斑点。\n' +
    '**四格的明度和饱和度要在同一档**，不能一格很亮一格很暗，' +
    '否则一换地形整屏的调子就跳。\n' +
    '**整体要压暗一档、要低对比**：这上面要摆红蓝两色的小兵，' +
    '底子一亮一花，兵就陷进去看不见了。\n' +
    '**严格的像素网格**：每个像素都是清晰的方块，边缘硬阶梯状，' +
    '绝不做抗锯齿、不做柔化、不做渐变；每一格的色板受限，只用 12 到 16 色。\n' +
    '画面中不得出现任何人物、船的侧舷与桅杆、建筑、文字、水印、边框或UI元素——' +
    '船板那一格只要**甲板本身的平面**，看不见船的轮廓也看不见水。';
}

/* 水战那格单独重出，不跟着整张重掷——另外三格已经对了，
   整张重出等于把对的也再赌一次。同样一张图的钱，保住三格。
   口径：俯视的连环船阵，船与船之间要露出水面，一眼看出是在水上打。 */
function shuiPrompt() {
  return '像素画（pixel art）风格的**地面材质**，用于策略游戏战棋盘的地面。\n' +
    '**俯视的连环船阵**：几条战船并排系在一起，' +
    '甲板是横铺的深褐船板、板缝里填着发黑的麻絮与桐油，' +
    '船与船之间**露出深青色的水面**，水上有细碎的波纹与反光，' +
    '相邻的船帮之间连着铁链与搭过去的跳板，甲板上间或有铁环与盘起的缆绳。\n' +
    '**要一眼看出是在水上的船上打**——水面必须清楚地露出来，' +
    '不能只剩一片木地板。船与水的面积大约七比三。\n' +
    '**视角是完全的正俯视**——从正上方垂直往下看，' +
    '所以**不许有地平线、不许有天空、不许有船的侧舷与桅杆、不许有任何东西的侧面**。\n' +
    '**要能四边无缝平铺**：船的排列要均匀、要铺满整幅，' +
    '**不许有一条特别大的主船或一个显眼的主体物**——平铺开来会变成规律的斑点。\n' +
    '**整体要压暗一档、要低对比**：这上面要摆红蓝两色的小兵，' +
    '底子一亮一花，兵就陷进去看不见了。\n' +
    '**严格的像素网格**：每个像素都是清晰的方块，边缘硬阶梯状，' +
    '绝不做抗锯齿、不做柔化、不做渐变；色板受限，只用 12 到 16 色。\n' +
    '画面中不得出现任何人物、建筑、文字、水印、边框或UI元素。';
}

const buildShui = () => ({
  id: 'cgd_shui', category: 'clashground', label: '阵型战地面·水战（连环船）',
  source: null, size: '1024x1024',
  prompt: shuiPrompt(), status: 'idle', attempts: 0,
});

const buildGround = () => ({
  id: 'cgd_sheet', category: 'clashground', label: '阵型战地面·四种（2×2）',
  meta: { 格数: 4 },
  source: null, size: '1024x1024',
  prompt: groundPrompt(), status: 'idle', attempts: 0,
});

/* ── 会动的地面 ────────────────────────────────────────────────────────
   一种地形一张 1024×1024，切 2×2 = 四帧、每格 512。
   和攻城背景同一套路数，但多一条硬约束：**每一帧还得各自四边无缝平铺**，
   因为这是铺满整个战棋盘的贴图，不是一张整幅的画。
   所以「不许有显眼的主体物」和「四帧逐像素一致」两条要同时满足。

   岩石和石板本身不动——山地和城郭只让石缝里的草、积水的反光动一动，
   石头跟着抖那是地震不是风。 */
const ANIM = {
  ping: '草叶的梢，按顺序朝同一侧倒伏再回来，像一阵风从同一个方向扫过整片草地；' +
        '草根与土不动',
  shui: '船与船之间那些水面的波纹与反光，四帧里朝同一方向推移、闪动；' +
        '**船板、铁链、缆绳、铁环一个像素都不许动**',
  shan: '石缝里那些稀疏的草与苔，梢头轻轻摇动；' +
        '**岩石本身、石头的层理与裂纹一个像素都不许动**',
  gong: '车辙里那几摊积水的反光，四帧里细碎地挪动；' +
        '**夯土、碎石、青石板与车辙的形状一个像素都不许动**',
};

function animPrompt(key) {
  const c = CELLS.find(x => x[0] === key);
  return '像素画（pixel art）风格的**四帧循环动画表**，' +
    '画的是策略游戏战棋盘的地面材质。\n' +
    '**画面严格划分成 2 列 × 2 行、共 4 个等大的方格**，每格 512×512，' +
    '格与格之间不画边框线也不画分隔线。\n' +
    '**这四格是同一块地面的连续四帧**：同样的构图、同样的纹理排布、同样的光照，' +
    '**就像同一台架死的摄影机连拍的四张，四格叠在一起要能严丝合缝地重合。**\n' +
    '**四格之间只有这一样在动：**' + ANIM[key] + '。\n' +
    '**除此之外一个像素都不许变。** 动的幅度要**小**——是微风与水光，不是狂风。\n\n' +
    '【这块地面是什么】' + c[1] + '：' + c[2] + '。\n\n' +
    '**视角是完全的正俯视**——从正上方垂直往下看地面，' +
    '**不许有地平线、不许有天空、不许有远景、不许有任何东西的侧面**。\n' +
    '**每一格都要能四边无缝平铺**：纹理要均匀铺满整格，' +
    '**不许有一个显眼的主体物**（一块大石头、一个大水坑、一条特别大的船都不行）——' +
    '平铺开来就会变成一片规律的斑点。\n' +
    '**整体要压暗一档、要低对比**：这上面要摆红蓝两色的小兵，' +
    '底子一亮一花，兵就陷进去看不见了。\n' +
    '**严格的像素网格**：每个像素都是清晰的方块，边缘硬阶梯状，' +
    '绝不做抗锯齿、不做柔化、不做渐变；色板受限，只用 12 到 16 色。\n' +
    '画面中不得出现任何人物、建筑、文字、水印、边框或UI元素。';
}

const buildAnim = k => ({
  id: 'cga_' + k, category: 'clashground',
  label: '阵型战地面动画·' + CELLS.find(x => x[0] === k)[1],
  meta: { 地形: CELLS.find(x => x[0] === k)[1], 帧数: 4 },
  source: null, size: '1024x1024',
  prompt: animPrompt(k), status: 'idle', attempts: 0,
});

const buildAnims = () => CELLS.map(c => buildAnim(c[0]));

module.exports = { CELLS, ANIM, buildGround, groundPrompt, buildShui, shuiPrompt,
                   animPrompt, buildAnim, buildAnims };
