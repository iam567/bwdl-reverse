/* 生成条目：node newofficers.js <officers-extra.csv> > items-extra.json */
function build(csvPath) {
  const fs = require('node:fs'), os = require('node:os'), path = require('node:path');
  const { buildPortraits, SOVEREIGN } = require('./build-catalog.js');
  Object.assign(SOVEREIGN, SOVEREIGN_EXTRA);
  const rows = fs.readFileSync(csvPath, 'utf8').split(/\r?\n/).filter(Boolean).map(l => l.split(','));
  const label = {};
  for (const r of rows) { label[r[0]] = r[1]; r[1] = PROMPT_NAME[r[1]] || r[1]; }
  const tmp = path.join(os.tmpdir(), 'officers-extra-prompt.csv');
  fs.writeFileSync(tmp, rows.map(r => r.join(',')).join('\n'));
  return buildPortraits(tmp).map(it => {
    const id = it.id.split('_')[1];
    return { ...it, label: label[id], source: null, status: 'idle', attempts: 0 };
  });
}
module.exports = { FEMALE_IDS, PROMPT_NAME, build };
if (require.main === module) process.stdout.write(JSON.stringify(build(process.argv[2]), null, 1));
