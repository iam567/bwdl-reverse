const pick = (arr, id, stride) => arr[(id * stride) % arr.length];

/* 年龄优先用数据推：后辈武将（登场年 >189）偏年轻，体力低偏年长 */
function ageOf(id, year, tili) {
  if (year >= 192) return AGE[0];
  if (year >= 190) return AGE[(id % 2)];
  if (tili && tili <= 55) return AGE[4];
  if (tili && tili <= 70) return AGE[3];
  return AGE[2 - (id % 2)];
}

/* 组装一个人的体貌描述 */
function physique(name, id, year, tili, isFemale) {
  if (APPEARANCE[name]) return APPEARANCE[name];
  if (isFemale) {
    /* 女性只取年龄/脸型/肤色/发式，不取须式 */
    return [ageOf(id, year, tili).replace('须发斑白，', '').replace('，须发斑白', ''),
            pick(FACE, id, 7), pick(SKIN, id, 3), pick(HAIR, id, 5)].join('，');
  }
  return [ageOf(id, year, tili), pick(FACE, id, 7), pick(SKIN, id, 3),
          pick(BEARD, id, 11), pick(HAIR, id, 5), pick(BUILD, id, 13),
          pick(MARK, id, 17)].join('，');
}
