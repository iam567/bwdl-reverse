function poseItem(key) {
  const [label, desc] = POSES[key];
  const base =
    PX + '\n\n【角色】' + LOOK +
    '\n\n【这一帧的姿势】' + desc + '。\n\n' + NEG;
  if (key === 'f5') return base;              // 母版自己不带参考图
  return '参考图里是这名骑将的待机姿势。' +
    '**画同一个人、同一匹马、同一套盔甲与配色**，只改动作：' + desc + '。' +
    '**不要换人、不要换马、不要改盔甲样式或颜色、不要改画风。**' +
    '\n\n' + PX + '\n\n' + NEG;
}

function buildDuelItems() {
  const out = [];
  out.push({
    id: seedId, category: 'duel', label: '单挑·骑将母版（待机）',
    meta: { 帧: 5, 用途: '其余 14 帧的参考图' },
    source: null, size: '1024x1024', background: 'transparent', prompt: poseItem('f5'),
    status: 'idle', attempts: 0,
  });
  for (const key of Object.keys(POSES)) {
    if (key === 'f5') continue;
    out.push({
      id: 'duel_' + key, category: 'duel',
      label: '单挑·' + POSES[key][0],
      meta: { 帧: Number(key.slice(1)) },
      source: null, size: '1024x1024', background: 'transparent', refItem: seedId,
      prompt: poseItem(key), status: 'idle', attempts: 0,
    });
  }
  return out;
}

