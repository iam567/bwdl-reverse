function build(items) {
  const tpl = items.find(i => i.id === 'card_2').prompt;
  const head = tpl.slice(0, tpl.indexOf('画面情境'));
  const tail = tpl.slice(tpl.indexOf('避免：'));
  const avatarTpl = items.find(i => i.id === 'avatar_2').prompt;
  const out = [];
  for (const [id, label, look, scene] of PEOPLE) {
    out.push({ id: 'card_' + id, category: 'card', label: '自建·' + label, meta: { 自建: true },
      source: '/source/avatar/' + id + '.png', size: '1024x1536',
      prompt: head + '画面情境：' + scene + '。光线：左上主光加右侧冷调轮廓光。\n\n主体：一位汉末' + label + '。体貌：' + look + '。以参考图的面孔、发型与头饰为准。\n\n' + tail,
      status: 'idle', attempts: 0 });
    out.push({ id: 'avatar_' + id, category: 'avatar', label: '自建·' + label, meta: { 自建: true },
      source: '/source/avatar/' + id + '.png', size: '1024x1024', refItem: 'card_' + id,
      prompt: avatarTpl, status: 'idle', attempts: 0 });
  }
  for (const [id, g, label, look, scene] of EXTRA) {
    out.push({ id: 'card_' + id, category: 'card', label: '自建·' + label, meta: { 自建: true, 性别: g },
      source: null, size: '1024x1536',
      prompt: head + '画面情境：' + scene + '。光线：左上主光加右侧冷调轮廓光。\n\n主体：一位汉末' + label + '（' + g + '性）。体貌：' + look + '。\n\n' + tail,
      status: 'idle', attempts: 0 });
    out.push({ id: 'avatar_' + id, category: 'avatar', label: '自建·' + label, meta: { 自建: true, 性别: g },
      source: null, size: '1024x1024', refItem: 'card_' + id,
      prompt: avatarTpl, status: 'idle', attempts: 0 });
  }
  return out;
}
