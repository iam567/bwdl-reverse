function prompt(skinKey, poseKey) {
  const look = SKINS[skinKey][2];
  const [, desc] = POSES[poseKey];
  if (poseKey === 'f5')
    return PX + '\n\n【角色】' + look + '\n\n【姿势】' + desc + '。\n\n' + NEG;
  return '参考图里是这名武将的待机姿势。' +
    '**画同一个人、同一匹马、同一套盔甲与配色、同一件兵器**，只改动作：' + desc + '。' +
    '**不要换人、不要换马、不要改盔甲或兵器的样式与颜色、不要改画风。**' +
    '\n\n' + PX + '\n\n' + NEG;
}

