'use strict';
/* 阵型战那几条 UI 的底图。
   风格接着单挑面板（duel_panel）那一套走：汉代木牌、黄铜窄边、四角铆钉、像素画。

   做成**九宫格（9-slice）可拉伸**的四张通用底图，而不是一屏一张：
   顶栏、底部兵数栏、菜单竖条、小地图外框，尺寸各不相同也常改，
   一屏一张的话每改一次布局就得重出一次图。
   九宫格的前提是「四条边等宽同纹、四个角完全对称、中间大片干净」——
   这三句必须写死在提示词里，不然拉伸出来花纹会歪、会错位。 */

const PX =
  '**严格的像素网格**：每个像素都是清晰的方块，边缘硬阶梯状，' +
  '绝不做抗锯齿、不做柔化、不做渐变；色板受限，靠有限色阶表现明暗。';

const NINE =
  '这张图会被程序按**九宫格拉伸**，所以必须满足三条：' +
  '**（一）上下左右四条边一样宽、花纹完全相同；' +
  '（二）四个角完全对称，旋转 90 度能对上；' +
  '（三）四条边之间的中间区域是一整片平整、干净、没有任何花纹和分格线的板面。**\n' +
  '**边框必须很细**：只是一道收边的线脚，不是宽板条。' +
  '**线脚的宽度不超过画面边长的二十五分之一**，' +
  '中间干净的板面要占到整幅画面的九成以上。' +
  '（九宫格拉伸时四条边是不跟着拉的——边越厚，中间留给文字的地方越少，' +
  '字就只能缩小、还容易压到边上。所以宁可细，不可厚。）';

const NO = '画面中不得出现任何文字、字母、汉字、数字、签名、水印。' +
           '除了这一块底板什么都不要画，**不要画表示透明的灰白棋盘格**。';

const ITEMS = [
  ['plate', '通用面板底',
   '一块汉代风格的木牌：**深褐色木纹**的板面，四边只包着一道**极细的黄铜线脚**。' +
   '**四个角不要铆钉、不要转角花纹、不要任何装饰**——就是四条细线收个边。' +
   '板面略有磨损和木纹的明暗变化，但整体要暗、要沉、要平，' +
   '因为上面要压白色的文字，底子花了字就看不清。'],

  ['btn', '菜单按钮底',
   '一条**不透明的实心木片**：整块板面是干净平整的褐色木头，比面板亮一档，' +
   '四周只有一道极细的深色描边。' +
   '**板面必须是实心的、从头到尾填满的——这是一块木片，不是一个空心的框。' +
   '绝对不能把中间画成透明或镂空的。**' +
   '不要金线、不要双重线脚、不要高光条、不要斜面倒角、不要铆钉、不要圆角花纹——' +
   '素一点，它只是让文字有个落脚的底，不是画面的主角。'],

  ['portrait', '武将头像框',
   '一个方形的**头像外框**：黄铜錾花的边框，四角是汉代风格的云雷纹转角，' +
   '上沿正中有一枚小小的兽首铺首衔环。' +
   '**框的正中间是一个完整的正方形空洞，必须完全透明**——' +
   '那里稍后要放武将的头像，所以**洞里一个像素都不要画**，' +
   '也不要画底色、不要画灰白棋盘格。框身的宽度约占画面边长的七分之一。'],

  ['mapbg', '小地图内衬',
   '一整块**深色的旧皮革**质感底纹，用作小地图的衬底：近乎全暗的赭褐色，' +
   '有细微的革纹与磨损，没有边框、没有花纹、没有高光块。' +
   '整块要**极暗、极平**——上面要点白色和赭红的小方块表示双方兵棋，' +
   '底纹一旦花了就看不清棋子了。四边要能无缝平铺。'],
];

function uiPrompt(key) {
  const it = ITEMS.find(x => x[0] === key);
  const nine = key === 'mapbg' ? '' : (key === 'portrait' ? '' : NINE);
  return '像素画（pixel art）风格的 UI 底板，用于中式历史策略游戏的战斗界面。\n' +
    it[2] + '\n' + PX + '\n' + nine + '\n' + NO;
}

const buildUi = k => {
  const it = ITEMS.find(x => x[0] === k);
  return {
    id: 'bui_' + k, category: 'battleui', label: '战斗界面·' + it[1],
    meta: { 用途: it[1] },
    source: null, size: '1024x1024', background: 'transparent',
    prompt: uiPrompt(k), status: 'idle', attempts: 0,
  };
};

const buildBattleUi = () => ITEMS.map(i => buildUi(i[0]));

module.exports = { ITEMS, buildUi, buildBattleUi, uiPrompt };
