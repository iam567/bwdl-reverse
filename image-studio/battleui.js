/* 信息栏那四行原来只写「体 骑 弓 步」四个字，压不住整块面板。
   改成四个小图标，一张 1024 切 2×2、每格 512，不单独出四张。
   「体」是武将本人的体力，所以用将盔；骑弓步是三种兵，
   辨识点跟场上的小兵对齐（马首 / 弓 / 盾戟），看一眼就能对上号。 */
