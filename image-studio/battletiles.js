/* ---------- 地形四格表（一张图出四格，切开用） ----------
   为什么合成一张：一个地形一张图，五个主题就是几十张，烧钱且风格难统一。
   合成一张还有个好处——四格共用一套色板是写在同一张画面里的硬约束，
   模型没法让平地和山地各走各的色调。

   画法分两类，这是这一版最要紧的改动：
     平地、水  —— **满铺无缝**，纹理铺到四边、自己和自己能接上；
     山、林    —— **画在平地上**，四条边留着和平地一样的素地面，特征只占中间六七成。
   原版就是后一种（山是「绿地上拱起一个黑三角」、林是「土地上长一棵树」），
   所以原版的格子拼起来边缘是连着的；我们原先四张全是满铺纹理，
   各画各的色调，拼一起就是一道道硬边。 */
