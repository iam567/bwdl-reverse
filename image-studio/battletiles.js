function buildThemeTiles(theme) {
  const T = THEMES[theme];
  return SLOTS.map(([code, slot, label]) => ({
    id: 'bt_' + theme + '_' + slot, category: 'battletile',
    label: '战场地块·' + T.name + '·' + label,
    meta: { 主题: T.name, 地形码: code, 槽位: slot },
    source: null, size: '1024x1024',
    ...(['wuku','cang','yao','castle'].includes(slot) ? { background: 'transparent' } : {}),
    prompt: slot === 'castle' ? castlePrompt(theme) : tilePrompt(theme, slot, T[slot]),
    status: 'idle', attempts: 0,
  }));
}

