/* ── 会动的背景 ────────────────────────────────────────────────────────
   一张 1024×1536 切 2 列 × 2 行 = 四帧，每帧 512×768（和整幅一样的竖版比例）。
   四帧循环播，旗子飘、云平移、草木摆。

   这件事和单挑立绘那套「一图多帧」正好相反：立绘是每格**本来就该不一样**，
   背景是四格必须**逐像素一致**、只有三样东西在动。
   模型很容易画成四张构图略有差别的图，切出来一播整幅画面都在抖，
   所以下面那三句「能重叠对齐 / 一个像素都不许变 / 架死的摄影机」是要害，不能删。

   代价：每帧只有 512×768，是静态那版的一半分辨率。 */
/* 会动的是哪三样，按地域定——不是每座城都有旗子。
   西域是风沙口岸，城头挂旗不合适；南中是夷寨，动的是图腾杆上的彩羽。
   每条都写成「四帧各是什么相位」，模型才知道这是一组连续帧而不是四张随机图。 */
