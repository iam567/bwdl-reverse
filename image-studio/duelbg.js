function animPrompt(id) {
  const c = CITIES[id];
  const tk = CITY_THEME[id], s = SIEGE[tk];
  const mv = MOTION[tk].map((m, i) => `（${'一二三四'[i]}）${m}；`).join('\n');
  return '像素画（pixel art）风格的**四帧循环动画表**，用于策略游戏的战斗背景。\n' +
    '**画面严格划分成 2 列 × 2 行、共 4 个等大的方格**，每格 512×768，' +
    '格与格之间不画边框线也不画分隔线。\n' +
    '**这四格是同一个地方、同一时刻的连续四帧**：同一座城墙、同一片天、同一处地面，' +
    '构图、透视、光照、每一块石头每一丛草的位置都必须完全一致——' +
    '**就像同一台架死的摄影机连拍的四张，四格叠在一起要能严丝合缝地重合。**\n' +
    '**四格之间只有下面这几样在动：**\n' + mv + '\n' +
    '**除此之外一个像素都不许变**：城墙的轮廓与斑驳、城门的位置、地面的坑洼与车辙、' +
    '远山的形状、光影的明暗，四格必须一模一样。\n' +
    '会动的那几样也要**小幅度**——是微风与远处的动静，不是狂风，' +
    '四帧连起来看要像同一个瞬间的呼吸。\n\n' +
    '【这是攻打' + c[1] + '的城下之战】\n' +
    '城墙：' + s.wall + '。\n' +
    '城外的地貌：' + c[3] + '。\n' +
    '时节与天光：' + c[2] + '。\n' +
    '脚下的空地：' + s.ground + '。\n' +
    '每一格都是：**上三分之二是远景与城墙，下三分之一是一块干净平整的空地**，' +
    '空地上没有任何物件、没有人物。\n\n' +
    '【时代形制】东汉末年：夯土高台基上的木构，屋顶平缓的悬山或庑殿，' +
    '铺青灰筒瓦或茅草，檐口只微微起翘——不要明清的飞檐翘角、斗拱彩画、琉璃瓦，' +
    '不要红灯笼、佛塔与庙宇。\n' +
    '**构图要往中间收**：最终会按手机竖屏裁切，每格左右各有可能被裁掉三分之一，' +
    '城门、城楼放在每格正中那一竖条里。\n' +
    '**严格的像素网格**，硬边、不做抗锯齿与渐变，色板受限。整体调子偏暗。\n' +
    '画面中不得出现任何人物、马匹、车辆、文字、水印、边框或UI元素。';
}

